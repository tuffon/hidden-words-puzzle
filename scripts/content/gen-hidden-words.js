// Generator for src/constants/hiddenWords.ts
// Reads the two JSON inputs, emits HIDDEN_WORDS (verbatim text) + a
// seeded-Fisher-Yates DAILY_ORDER baked as a literal (no runtime randomness).
const fs = require('fs')
const path = require('path')

const SCRATCH = __dirname
const OUT = process.argv[2]
if (!OUT) {
  console.error('usage: node gen-hidden-words.js <output-ts-path>')
  process.exit(1)
}

const words = JSON.parse(
  fs.readFileSync(path.join(SCRATCH, 'hidden-words-153.json'), 'utf8')
)
const curated = JSON.parse(
  fs.readFileSync(path.join(SCRATCH, 'hidden-words-curated.json'), 'utf8')
)

const wordById = new Map(curated.entries.map((e) => [e.id, e.word]))

const included = []
for (const p of words) {
  const w = wordById.get(p.id)
  if (w == null) continue // null / excluded
  included.push({
    id: p.id,
    collection: p.collection,
    number: p.number,
    word: w,
    text: p.text,
    link: p.link,
  })
}

// --- validation (fail loud rather than emit a bad file) ---
const seen = new Set()
for (const e of included) {
  if (!/^[a-z]{5}$/.test(e.word)) throw new Error(`bad word ${e.id}:${e.word}`)
  if (seen.has(e.id)) throw new Error(`dup id ${e.id}`)
  seen.add(e.id)
  const re = new RegExp('\\b' + e.word + '\\b', 'i')
  if (!re.test(e.text)) throw new Error(`word not in text ${e.id}:${e.word}`)
  if (!e.link.startsWith('https://www.bahai.org/'))
    throw new Error(`bad link ${e.id}`)
  if (e.collection !== 'arabic' && e.collection !== 'persian')
    throw new Error(`bad collection ${e.id}`)
}

// --- seeded PRNG (mulberry32) + Fisher-Yates over the ids ---
function mulberry32(a) {
  return function () {
    a |= 0
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
const rand = mulberry32(0x1a2b3c4d)
const order = included.map((e) => e.id)
for (let i = order.length - 1; i > 0; i--) {
  const j = Math.floor(rand() * (i + 1))
  ;[order[i], order[j]] = [order[j], order[i]]
}

// --- emit TS ---
const esc = (s) => JSON.stringify(s)
let out = ''
out += '// AUTO-GENERATED by scratchpad/gen-hidden-words.js — do not edit by hand.\n'
out += '// Source: hidden-words-153.json (verbatim text) + hidden-words-curated.json (answers).\n'
out += '// Sacred text: the `text` field is VERBATIM and must never be edited.\n\n'
out += "export type HiddenWord = {\n"
out += '  id: string\n'
out += "  collection: 'arabic' | 'persian'\n"
out += '  number: number\n'
out += '  word: string\n'
out += '  text: string\n'
out += '  link: string\n'
out += '}\n\n'
out += 'export const HIDDEN_WORDS: HiddenWord[] = [\n'
for (const e of included) {
  out += '  {\n'
  out += `    id: ${esc(e.id)},\n`
  out += `    collection: ${esc(e.collection)},\n`
  out += `    number: ${e.number},\n`
  out += `    word: ${esc(e.word)},\n`
  out += `    text: ${esc(e.text)},\n`
  out += `    link: ${esc(e.link)},\n`
  out += '  },\n'
}
out += ']\n\n'
out += '// Seeded Fisher-Yates permutation (mulberry32, seed 0x1a2b3c4d) — baked, deterministic.\n'
out += 'export const DAILY_ORDER: string[] = [\n'
for (const id of order) {
  out += `  ${esc(id)},\n`
}
out += ']\n'

fs.writeFileSync(OUT, out)
console.log(`wrote ${OUT}: ${included.length} words, DAILY_ORDER len ${order.length}`)
